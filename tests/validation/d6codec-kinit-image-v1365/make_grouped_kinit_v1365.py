#!/usr/bin/env python3
"""Build a test-only grouped D6CODEC KINIT stream from a real KINIT image.

Input is the production uncompressed KINIT `kinit.words` generated by
mkimage.sh: SIXBIT DAIMON, image_words,,entry_offset, then image words.
The output has the same two header words and a new compressed_words,,0
third header word, followed by grouped v053 tokens. Never overwrite
the input or a production .d6lz.words / boot-media artifact.
"""

import importlib.util
import os
import pathlib
import sys

MASK36 = (1 << 36) - 1
MASK18 = (1 << 18) - 1
DAIMON_MAGIC = 0o444151555756
IMAGE_BASE = 0o30000


def reference():
    testkit = pathlib.Path(__file__).resolve().parents[3]
    path = testkit / "tests/validation/d6codec-current-corpus-v1359/generate-v1359.py"
    spec = importlib.util.spec_from_file_location("host_golden_v1359", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def load_words(path):
    result = []
    with pathlib.Path(path).open("r", encoding="ascii") as inp:
        for n, row in enumerate(inp, 1):
            raw = row.strip()
            if not raw or len(raw) > 12 or any(c not in "01234567" for c in raw):
                raise ValueError("invalid octal input at line %d" % n)
            value = int(raw, 8)
            if value > MASK36:
                raise ValueError("word exceeds 36 bits")
            result.append(value)
    return result


def build(source, dest, core_words, stack_words):
    source = pathlib.Path(source).resolve()
    dest = pathlib.Path(dest).resolve()
    if source == dest:
        raise ValueError("refusing to overwrite source image")
    if dest.name.endswith(".d6lz.words") or dest.name == "kinit.words":
        raise ValueError("refusing to replace a production image")
    words = load_words(source)
    if len(words) < 4 or words[0] != DAIMON_MAGIC:
        raise ValueError("invalid DAIMON KINIT header")
    count, entry = words[1] >> 18, words[1] & MASK18
    payload = words[2:]
    if not 0 < count <= MASK18 or len(payload) != count or entry >= count:
        raise ValueError("malformed uncompressed KINIT extent or entry")
    if core_words not in (0o100000, 0o1000000):
        raise ValueError("unsupported physical profile")
    if stack_words < 1 or stack_words > MASK18:
        raise ValueError("invalid KINIT stack reserve")
    host = reference()
    compressed = host.encode(payload)
    if not 0 < len(compressed) <= MASK18:
        raise ValueError("compressed length not representable in header")
    if host.reference.decode(compressed, count) != payload:
        raise ValueError("independent host decoded stream mismatch")
    decoded_end = IMAGE_BASE + count
    staged_end = decoded_end + len(compressed)
    if decoded_end + stack_words > core_words:
        raise ValueError("KINIT leaves less than configured stack reserve")
    if staged_end > core_words:
        raise ValueError("compressed staging would exceed physical core")
    if dest.is_file():
        raise ValueError("test output already exists: " + str(dest))
    dest.parent.mkdir(parents=True, exist_ok=True)
    # Publish only after all validation and the host roundtrip succeed.
    temporary = dest.with_name(dest.name + ".tmp." + str(os.getpid()))
    try:
        with temporary.open("x", encoding="ascii") as out:
            for value in (words[0], words[1], len(compressed) << 18):
                out.write("%012o\n" % value)
            for value in compressed:
                out.write("%012o\n" % value)
        temporary.replace(dest)
    finally:
        if temporary.exists():
            temporary.unlink()
    print("KINIT_GROUPED_HOST_PASS U=%d C=%d entry=0%o decode_end=0%o stage_end=0%o core=0%o" %
          (count, len(compressed), IMAGE_BASE + entry, decoded_end,
           staged_end, core_words))


def main():
    if len(sys.argv) != 5:
        raise SystemExit("usage: make_grouped_kinit_v1365.py KINIT.words OUT.words CORE_OCT STACK_OCT")
    build(sys.argv[1], sys.argv[2], int(sys.argv[3], 8), int(sys.argv[4], 8))


if __name__ == "__main__":
    main()
