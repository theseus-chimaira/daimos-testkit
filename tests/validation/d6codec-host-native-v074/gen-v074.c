/* Deterministic C99 host stream generation for native PDP-6 decoder test. */
#include <stdint.h>
#include <stdio.h>
#include "d6codec-group-v071.h"
int main(void) {
    uint64_t src[350], compressed[800];
    size_t i, count;
    for (i = 0; i < 350; ++i)
        src[i] = i % 17 == 0 ? 0 : i % 17 < 6 ?
            UINT64_C(012345670123) : (uint64_t)(i * 761 + 123);
    src[0] = (UINT64_C(0111111) << 18) | UINT64_C(0222222);
    src[1] = (UINT64_C(0333333) << 18) | UINT64_C(0444444);
    for (i = 2; i < 90; ++i)
        src[i] = ((src[i-2] & UINT64_C(0777777)) << 18) |
            ((src[i-1] >> 18) & UINT64_C(0777777));
    if (d6codec_group_v072_encode(src, 350, compressed, 800, &count)) return 1;
    puts("/* Generated by host v072, independently decoded on PDP-6. */");
    puts(".data\n.globl v074_stream\nv074_stream:");
    for (i = 0; i < count; ++i)
        printf(" .word 0%012llo\n", (unsigned long long)compressed[i]);
    printf(".globl v074_input_count\nv074_input_count: .word 0%012llo\n",(unsigned long long)count);
    puts(".globl v074_expected\nv074_expected:");
    for (i = 0; i < 350; ++i)
        printf(" .word 0%012llo\n",(unsigned long long)src[i]);
    return 0;
}
