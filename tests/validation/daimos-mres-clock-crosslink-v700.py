#!/usr/bin/env python3
"""Quantify clock cross-MRES patch sites and verify early provider order."""
from pathlib import Path
import re
import sys

root=Path(sys.argv[1])
kernel=root/'system/kernel'
table=(kernel/'modules/module_table.s').read_text()
make=(root/'system/boot/pdp6/Makefile').read_text()
syscall=(kernel/'proc/syscall_dispatch_pdp6.s').read_text()
gateway=(kernel/'drivers/pclk_gateway.s').read_text()
assert table.index('pclkclock_minit,,pclk_mres_package') < table.index('memfs_minit,,memfs_mres_package')
assert table.index('softclock_minit,,softclock_mres_package') < table.index('d6fs_minit,,d6fs_mres_package')
sites={}
for family, files in {
    'memfs': ['fs/memfs_runtime.s'],
    'd6fs': ['fs/d6fs_runtime.s','fs/d6fs_provider_mutation.s',
             'fs/d6fs_provider_namespace_pdp6.s']}.items():
    for filename in files:
        source=(kernel/filename).read_text()
        matches=list(re.finditer(r'^\s*pushj\s+17,wall_time36\b',source,re.M))
        if matches:
            sites[filename]=[source.count('\n',0,m.start())+1 for m in matches]
assert sum(map(len,sites.values()))==6
assert 'D6FS_NOW() wall_time36()' in (kernel/'fs/d6fs_provider.c').read_text()
assert '.word   native_sys_exec,,wall_time36' in syscall
assert 'jrst    wall_clock_set' in syscall
assert 'jrst wall_time36_unset' in gateway
assert 'jrst wall_clock_set_unavailable' in gateway
# These are source occurrences, NOT necessarily the entirety of link-time
# calls generated by the C compiler; no resident saving is claimed.
for filename,lines in sites.items():
    print('%s: %s' %(filename,','.join(map(str,lines))))
print('v700: six explicit assembly calls, compiler-generated C calls still require inspection')
print('v700: syscall has one packed table entry and one SETTIME tail jump')
print('v700: provider precedes both filesystem MRES installs: PASS')
